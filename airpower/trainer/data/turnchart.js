/**
 * 시작 속도에 해당하는 차트 열 인덱스.
 * 2.5 이하 → 2열, 24 초과 → 24+열, 표에 없는 중간 속도 → 낮은 쪽 열.
 */
export function speedColumn(speed) {
  if (speed <= 2.5) return 0;
  if (speed > 24) return SPEED_COLUMNS.length - 1;
  let idx = 0;
  for (let i = 0; i < SPEED_COLUMNS.length; i++) {
    if (SPEED_COLUMNS[i] <= speed) idx = i;
  }
  return idx;
}

/**
 * 선회 요구 비용.
 * @returns {{fp:number}|{degrees:60}|null} null = 해당 선회율 사용 불가
 */
export function turnCost(band, speed, rate) {
  const row = CHART[band]?.[rate];
  if (!row) return null;
  const v = row[speedColumn(speed)];
  if (v === 'NA') return null;
  if (v === 60) return { degrees: 60 };
  return { fp: v };
}

